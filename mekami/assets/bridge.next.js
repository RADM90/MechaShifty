/* 다리 — 효과표가 쌓아 둔 버프를 대미지 공식의 여섯 칸에 배치한다. 순수 함수.

   1세대와 2세대가 **진짜로 다른 곳이 여기다.** 사격 기계장치는 실측이라 그대로 옮기면
   되고, 효과표도 거의 그대로 얹힌다. 갈리는 것은 "이 버프가 어느 칸에 들어가는가" 뿐이다.

   옮겨간 것 넷:

     · 파츠·관통·지속·방어력 무시·투사체·저지 부위 같은 "~ 대미지 증가"
       1세대: 서로 곱했다 `(1+a)(1+b)`   ->   2세대: **한 칸에서 더한다** `1+a+b`
     · 분배 대미지 증가
       1세대: 공격 쪽 타입 배수         ->   2세대: **적이 받는 칸**
     · 차지 대미지 증가
       1세대: 별도 레이어               ->   2세대: **풀차지 배율과 같은 칸에서 합산**
     · 크리티컬
       1세대: 기댓값(확률 × 배율)       ->   2세대: **타격마다 난수**

   ── 조건부라는 것이 요점이다 (메커니즘 9) ──────────────────

   버프형 칸에 들어온 항이라고 다 더하는 게 아니다. **그 타격이 해당 종류일 때만** 더한다 —
   파츠를 안 때리면 파츠 증댐이 안 붙는다. 그래서 타격마다 어떤 종류인지를 알아야 하고,
   그 정보는 효과표의 `hit.type` 과 무기 제원에서 나온다. */

import { TYPE_DMG } from './effects.js';
import { 종류, 적용 } from './formula.next.js';

/* ── 타격의 성격을 유도한다 ────────────────────────────────── */

/* 효과표는 1세대 어휘로 적혀 있다. 다행히 **2세대가 필요한 정보가 이미 들어 있다:**

     hit.kind === 'burst'   -> 버스트 스킬 본체
     hit.gauge === false    -> "추가 대미지" 리더 (초안 생성기가 원문의 `추가` 를 보고 달았다)
     그 밖                   -> 스킬 투사체

   그래서 효과표 199장을 다시 쓰지 않는다. 유도로 얹는다.

   `hit.코어명중` 은 새 필드다 — 원문이 "코어 명중 대미지" 라고 적은 타격 (신데렐라 :
   크리스탈 웨이브 2스킬 한 건). */
export function 타격성격(hit) {
  const 종 = hit.gauge === false ? 종류.추가
    : hit.kind === 'burst' ? 종류.버스트스킬
      : 종류.스킬;
  return {
    종류: 종,
    타입: [].concat(hit.type || []),
    코어명중: hit['코어명중'] === true,
    /* 게이지를 채우는 투사체인가. 리더는 이미 나간 총알에 얹히는 판정이라 아니다
       (메커니즘 4). */
    투사체: 종 !== 종류.추가,
  };
}

/* 평타의 성격. 무기 제원이 정한다.

   · 폭발 무기(RL)는 평타 자체가 폭발이라 "발사체 폭발 대미지 ▲" 를 받는다
   · "일반 공격을 방어력 무시 대미지로 적용" (은화 : 택티컬 업)이 걸려 있으면 평타의
     타입 자체가 바뀐다 */
export function 평타성격(shot, buff = {}) {
  const 타입 = ['normalAtkPct', ...(shot.types || [])];
  if (shot.explosionRange > 0) 타입.push('explosionDmg');
  if (buff.normalAsTrue > 0) 타입.push('trueDmg');
  return {
    종류: 종류.평타,
    타입,
    코어명중: false,          // 평타는 상황(코어명중가능)이 판정한다
    투사체: true,
    무기: shot.weapon,
    차지: shot.control === 'charge',
  };
}

/* ── 버프를 칸에 배치한다 ──────────────────────────────────── */

/* "~ 대미지 증가" 계열 중 **버프형 칸(③)** 에 들어가는 것들. 타격이 그 타입일 때만 더한다.

   `distributedDmg` 는 여기 없다 — 적이 받는 칸(⑥)으로 갔다.
   `chargeDmg` 도 없다 — 차지 칸(④)으로 갔다. */
const 버프형_조건부 = [...TYPE_DMG].filter(t => t !== 'distributedDmg' && t !== 'chargeDmg');

/* 이 둘은 **적의 생김새**가 조건이다. 파츠가 붙은 보스인지, 노란 저지 부위가 있는지는
   때리는 쪽이 정하는 것이 아니라 상대가 정한다. 값은 전투 조건으로 받는다.
   켜면 그 타격이 전부 그 부위에 맞은 것으로 본다 — 상한값이다 (메커니즘 13 과 같은 결). */
const 적생김새 = { partsDmg: '파츠있음', blockDmg: '저지부위있음' };

/* 무기의 코어 배율을 보너스로. CDN 의 `coreDamage` 가 200(%) 이면 +1.0 이다. */
const 코어기본 = shot => ((shot && shot.coreDamage) || 200) / 100 - 1;

/* 타격 한 대의 여섯 칸 입력을 만든다.

     buff     계열별로 합쳐진 버프 (엔진의 buckets)
     성격     타격의 성격 (타격성격 / 평타성격)
     상황     { 풀버스트, 교전거리, 코어명중가능, 우월코드, 적방어력 }
     shot     무기 제원 (코어 배율·풀차지 배율)
     크리     이 발이 크리가 터졌는가 (엔진이 난수로 굴려 넘긴다)
     계수     그 발의 배율 (평타 5.57% -> 0.0557, 버스트 6000% -> 60)

   돌려주는 것을 `formula.next.js` 의 `대미지()` 에 그대로 넣는다. */
export function 여섯칸({ buff = {}, 성격, 상황 = {}, shot = {}, 크리 = false, 계수 = 1, 공격력 = 0 }) {
  const 붙 = 적용({ ...성격, 무기: 성격.무기 || shot.weapon }, 상황);
  const 타입 = new Set(성격.타입 || []);

  /* **방어력 무시 대미지는 배수만 받는 게 아니라 뺄셈 방어력을 건너뛴다.**
     고방어 적에서 판을 뒤집는 자리라 배수와 같이 다뤄야 한다. (열린 물음 L — 그림에는
     안 적혀 있고 1세대에서 물려받았다. 1세대는 공격력 대비 방어력 3/4 조건에서 4배
     차이를 확인했고 커뮤니티 보고와 같은 크기였다.) */
  const 방어무시 = 타입.has('trueDmg');

  /* ③ 버프형 — **한 칸에서 더한다.** 해당하는 타입만 골라 넣는다 (메커니즘 9).

     조건이 두 가지로 갈린다.
       · **타격의 성격** — 관통·폭발·지속처럼 그 공격이 원래 그 종류인 것. `hit.type`
         이나 무기 제원에서 온다.
       · **적의 생김새** — 파츠·저지 부위. 그런 부위가 있고 그걸 때리느냐는 적에
         달렸지 타격에 달린 게 아니다. 그래서 전투 조건으로 받는다 (메커니즘 11 의
         코어 명중 가능과 같은 부류).
     둘을 섞어 `hit.type` 하나로 보면 파츠 증댐이 **영영 안 걸린다** — 평타에는 타입을
     적을 자리가 없기 때문이다. */
  const 버프증가 = [buff.damageUp || 0];
  for (const t of 버프형_조건부) {
    if (!buff[t]) continue;
    if (적생김새[t]) { if (상황[적생김새[t]]) 버프증가.push(buff[t]); continue; }
    if (타입.has(t)) 버프증가.push(buff[t]);
  }

  return {
    기본: {
      공격력,
      /* 시전자 기준 공격력은 퍼센트가 아니라 고정 가산이다 — 받는 쪽 공격력이 아니라
         **시전자의** 공격력에 비례하므로, 걸 때 재서 박아 둔 값이 그대로 들어온다. */
      가산: buff.atkFlat || 0,
      공증: [buff.atkPct || 0],
      상대방어력: 방어무시 ? 0 : (상황.적방어력 || 0),
      공격계수: 계수,
    },
    기본증가: {
      크리티컬: 크리,
      추가크뎀: [buff.critDmg || 0],
      /* 코어 보너스는 붙을 때만. 무기 배율(200% -> +1.0)에 "코어 대미지 증가" 를 더한다. */
      코어: 붙.코어 ? 코어기본(shot) + (buff.coreDmg || 0) : null,
      거리: 붙.거리,
      풀버스트: 붙.풀버스트,
    },
    버프증가,
    차지: {
      차지: 붙.차지,
      /* 풀차지 배율(250%/350%)과 "차지 대미지 증가" 가 **같은 칸에서 더해진다.** */
      풀차지배율: (shot.charge && shot.charge.fullDamage ? shot.charge.fullDamage : 100) / 100,
      추가차뎀: [buff.chargeDmg || 0],
      /* 얼마나 당겼나. 수동으로 끊어 쏘면 1 보다 작고, 그만큼만 이 칸을 받는다. */
      비율: 성격.차지비율 == null ? 1 : 성격.차지비율,
    },
    우월코드: {
      우월코드: !!상황.우월코드,
      추가우코: [buff.elemDmg || 0],
    },
    받는: {
      받는증가: [buff.receivedUp || 0],
      /* **분배 대미지 증가가 여기 있다** — 공격 쪽이 아니라 적이 받는 쪽이다.
         분배 공격일 때만 더한다. */
      분배증가: 타입.has('distributedDmg') ? [buff.distributedDmg || 0] : [],
      받는감소: [],
    },
    /* 순서 의무 위반 표식. 엔진이 그대로 경고로 올린다. */
    순서이상: 붙.순서이상,
  };
}

/* ── 어느 버프가 어느 칸으로 갔나 ──────────────────────────── */

