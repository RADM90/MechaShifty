/* 한 대의 대미지 — 시간도 DOM 도 모르는 순수 함수.

   메커니즘 5 로 받은 그림을 그대로 옮겼다. 여섯 칸이 곱해지고, **각 칸 안은 합**이다.

     (기본 데미지) × (기본 데미지 증가 계수) × (버프형 데미지 증가 계수)
                  × (차지 데미지 계수) × (우월코드 계수) × (상대방 받는 데미지 증가)

   칸마다 그림의 이름을 그대로 쓴다. 영어로 바꿔 놓으면 원본과 나란히 놓고 대조할 수가
   없고, 대조가 안 되면 어느 항이 어느 칸에 들어가야 하는지가 곧 흐려진다.

   ── 1세대와 달라진 곳 세 군데 ───────────────────────────────

   1세대는 파츠·관통·지속·방어력 무시·투사체 같은 "~ 대미지 증가" 를 **서로 곱했다**
   (`(1+a)(1+b)`). 그림은 **한 칸 안에서 더한다** (`1+a+b`). 겹칠수록 차이가 커진다.

   1세대는 풀차지 배율(250%/350%)을 그 발의 계수에 곱하고 "차지 대미지 증가" 를 따로
   된 레이어로 뒀다. 그림은 **둘을 한 칸에서 더한다**.

   1세대는 "분배 대미지 증가" 를 공격 쪽 타입 배수로 뒀다. 그림은 **적이 받는 칸**에
   두고, 거기서 "받는 대미지 감소" 를 뺀다.

   ── 어느 항이 붙는지는 타격의 성격이 정한다 (메커니즘 8·9) ──

   "평타냐 스킬이냐" 로 가르는 표가 아니다. 가르는 것은 그 타격이 **원문에서 무엇이라고
   선언되는가** 다. 신데렐라 : 크리스탈 웨이브 2스킬의 `[최종 공격력 833.79% 코어 명중
   대미지]` 는 스킬 타격이지만 원문이 "코어 명중" 이라 적었으므로 코어 보너스를 받는다.
   반대로 나유타의 `[기억 연소 : 사용 무기 변경]` 은 대미지 항이 아니라 아예 해당이 없다.

   그래서 타격마다 성격을 적고 (`타격` ), 붙일 항은 `적용()` 이 골라 준다. */

/* 그림에 적힌 기본 계수. */
export const BASE = {
  /* 기본 데미지 증가 계수 칸 */
  크리티컬: 0.50,        // 크뎀 수치 기본 50% (+α)
  거리: 0.30,            // 거리 보너스 30%
  풀버스트: 0.50,        // 풀버스트 보너스 50%
  /* 우월코드 계수 칸 */
  우월코드: 1.10,        // 110% (기본계수)
};

const sum = list => (list || []).reduce((s, v) => s + (v || 0), 0);

/* ── 타격의 성격 ───────────────────────────────────────────── */

/* 원문이 그 타격을 무엇이라고 부르는가. 효과표가 타격마다 이걸 적는다. */
export const 종류 = {
  평타: '평타',                    // 무기로 쏘는 것 (차지 포함)
  버스트스킬: '버스트스킬',          // "[최종 공격력 6000% 버스트 스킬 대미지]"
  추가: '추가',                    // "[최종 공격력 N% 추가 대미지]"
  스킬: '스킬',                    // 그 밖의 스킬 타격
};

/* 무기군별 적정거리. **RL 은 없다** — 거리 보너스를 영영 안 받는다.
   무기군을 보고 예외 처리하는 게 아니라, 표에 `null` 이 들어 있어 저절로 빠진다. */
export const 적정거리 = {
  AR: '중거리', SMG: '근거리', RL: null, SR: '원거리', MG: '중거리', SG: '근거리',
};

/* 이 타격에 어느 보너스가 붙는가 (메커니즘 8).

     타격 { 종류, 무기, 코어명중, 차지 }
     상황 { 풀버스트, 교전거리, 코어명중가능 }

   `코어명중` 은 그 타격이 원문에서 코어 명중이라고 선언됐는가다. 평타는 실제로 코어에
   맞으면 받으므로 `상황.코어명중가능` 이 그 판정을 대신한다 (열린 물음 I). */
export function 적용(타격 = {}, 상황 = {}) {
  const 평타 = 타격.종류 === 종류.평타;
  return {
    /* 코어에 맞았을 때. 코어가 없는 적이거나 노출돼 있지 않으면 안 붙는다. */
    코어: !!상황.코어명중가능 && (평타 || 타격.코어명중 === true),
    /* 무기군 적정거리와 교전거리가 맞을 때. 평타 기반. */
    거리: 평타 && 적정거리[타격.무기] != null
          && 적정거리[타격.무기] === 상황.교전거리,
    /* **타격이 들어간 순간 풀버스트가 켜져 있었나** — 그것뿐이다 (메커니즘 10).
       종류별 표가 아니다. "버스트 스킬 본체는 안 받는다" 는 예외 규칙이 아니라, 본체가
       풀버스트가 열리기 한 박자 전에 때려서 저절로 못 받는 것이다. 같은 이유로
       "추가 대미지" 는 열린 뒤에 때려서 받고, 슈팅 스타처럼 풀버스트를 가로질러
       지속되는 스킬은 그 구간에 들어간 타격만 받는다.

       그래서 **엔진이 순서를 지켜야 한다.** 어긋나면 조용히 1.5배가 붙으므로 아래에서
       `순서이상` 으로 짚어 준다. */
    풀버스트: !!상황.풀버스트,
    /* 차지는 무기의 차지 사격이라 평타다. */
    차지: 평타 && !!타격.차지,
    /* 있을 수 없는 조합. 버스트 스킬 본체는 풀버스트가 열리기 전에 때리므로, 이게
       참이면 엔진이 순서를 어긴 것이다 — 1세대가 조용히 틀려 있던 것과 같은 부류라
       조용히 넘기지 않고 짚는다. */
    순서이상: !!상황.풀버스트 && 타격.종류 === 종류.버스트스킬,
  };
}

/* ── ① 기본 데미지 ─────────────────────────────────────────
   공증 수치 = 기본 공격력 × {(100% + 추가 공증 수치) − 상대 방어력 계수} × 공격 계수

   **방어력은 곱이 아니라 뺄셈**이고, 버프까지 먹인 공격력에서 뺀다. 발당 대미지가
   낮은 무기군(SMG·MG)이 고방어 적에게 극단적으로 불리한 이유가 이것이다. */
export function 기본데미지({ 공격력, 가산 = 0, 공증 = [], 상대방어력 = 0, 공격계수 = 1 }) {
  /* `가산` 은 "시전자 기준 공격력 N% ▲" 가 남긴 값이다. 그 버프는 받는 쪽 공격력의
     퍼센트가 아니라 **시전자의 공격력**에 비례하므로, 걸 때 재서 박아 둔 고정 수치가
     들어온다. 그림의 공증 칸은 퍼센트라 여기 섞을 수 없어 항을 따로 뒀다.

     그 값을 잴 때 시전자의 **최종** 공격력을 쓰면 서로가 서로를 키우는 되먹임이
     생긴다 — 1세대가 그렇게 164초에 63배까지 갔다. 재는 것은 엔진 몫이고
     (`casterAtk`), 여기서는 이미 정해진 수를 받는다. */
  const 공격 = 공격력 * (1 + sum(공증)) + 가산;
  return { 유효공격력: 공격 - 상대방어력, 값: (공격 - 상대방어력) * 공격계수 };
}

/* ── ② 기본 데미지 증가 계수 ───────────────────────────────
   100% + 크뎀 + 코어 보너스 + 거리 보너스(30%) + 풀버스트 보너스(50%)

   **넷이 서로 곱하지 않고 더해진다.** 커뮤니티 실측이 이걸 못박아 준다:
     기본 2521 -> 크리 3781(×1.5) -> 코어 5042(×2.0) -> 코어+크리 6302(×2.5)
     -> 코어+크리+풀버 7563(×3.0)      즉 1 + 0.5 + 1.0 + 0.5 */
export function 기본증가({ 크리티컬 = false, 추가크뎀 = [], 코어 = null,
                          거리 = false, 풀버스트 = false }) {
  let v = 1;
  if (크리티컬) v += BASE.크리티컬 + sum(추가크뎀);
  /* 코어 보너스는 무기가 값을 들고 있다 (코어 대미지 200% -> +1.0). 여기 얼마를
     넣을지는 부르는 쪽 몫이라 숫자를 그대로 받는다. */
  if (코어 != null) v += 코어;
  if (거리) v += BASE.거리;
  if (풀버스트) v += BASE.풀버스트;
  return v;
}

/* ── ③ 버프형 데미지 증가 계수 ─────────────────────────────
   100% + 공격 + 파츠 + 관통 + 지속 + 방어력 무시 + 투사체 + 저지 부위 + (그 밖의 "~ 증가")

   **전부 한 칸 안에서 더해진다.** 1세대처럼 서로 곱하면 셋만 겹쳐도 결과가 눈에
   띄게 부푼다. 해당하는 항만 골라 넘기는 것은 부르는 쪽 몫이다 (열린 물음 F). */
export function 버프증가(증가목록 = []) {
  return 1 + sum(증가목록);
}

/* ── ④ 차지 데미지 계수 ────────────────────────────────────
   250% or 350% (캐릭별 상이) + 추가 차뎀 수치

   차지 공격이 아니면 이 칸은 100% 다. 풀차지 배율과 "차지 대미지 증가" 가 **같은 칸
   에서 더해지는** 것이 1세대와 다른 점이다.

   자료가 이 칸을 통째로 확인해 준다 (유튜브 "니케 모든 대미지 알아보기"):
   "100% 풀차지 공격이 250% 데미지를 입히는 상황에서 차지 데미지 150% 버프를 받으면
   풀차지 공격만 400%가 되는 것" — 250 + 150 = 400, 곱이 아니라 합이다.

   **덜 당기면 그만큼만 받는다.** 같은 자료가 "차지한 만큼 버프가 적용되기 때문에
   톡톡기로 공격하는 니케는 차지 데미지 옵션 효율을 제대로 받지 못한다" 고 짚는다.
   그래서 비율을 0 과 1 사이에서 **칸 전체에** 건다 — 풀차지 배율만 깎고 버프는 그대로
   두거나, 반대로 버프를 통째로 버리는 것이 아니다. */
export function 차지계수({ 차지 = false, 풀차지배율 = null, 추가차뎀 = [], 비율 = 1 }) {
  if (!차지) return 1;
  const 만충 = (풀차지배율 > 0 ? 풀차지배율 : 1) + sum(추가차뎀);
  const r = 비율 >= 1 ? 1 : (비율 > 0 ? 비율 : 0);
  return 1 + (만충 - 1) * r;
}

/* ── ⑤ 우월코드 계수 ───────────────────────────────────────
   110% (기본계수) + 추가 우코 수치. 우월코드가 아니면 100%. */
export function 우월코드계수({ 우월코드 = false, 추가우코 = [] }) {
  return 우월코드 ? BASE.우월코드 + sum(추가우코) : 1;
}

/* ── ⑥ 상대방 받는 데미지 증가 ─────────────────────────────
   100% + 받는 데미지 증가 + 분배 데미지 증가 − (상대방) 받는 데미지 감소

   **분배 대미지 증가가 여기 있다** — 공격 쪽이 아니라 적이 받는 쪽이다.
   그리고 감소는 더하는 게 아니라 **뺀다**. */
export function 받는증가({ 받는증가: 받 = [], 분배증가 = [], 받는감소 = [] }) {
  return 1 + sum(받) + sum(분배증가) - sum(받는감소);
}

/* ── 한 대 ─────────────────────────────────────────────────

   돌려주는 `칸` 은 여섯 칸의 값이다. 숫자 하나만 주면 틀렸을 때 어느 칸이 틀렸는지
   알 수가 없다 — 1세대에서 공격력이 63배로 부푼 것을 찾아낸 것도 이 분해였다. */
export function 대미지(input) {
  const 기본 = 기본데미지(input.기본 || {});
  const 칸 = {
    기본데미지: 기본.값,
    기본증가: 기본증가(input.기본증가 || {}),
    버프증가: 버프증가(input.버프증가),
    차지계수: 차지계수(input.차지 || {}),
    우월코드계수: 우월코드계수(input.우월코드 || {}),
    받는증가: 받는증가(input.받는 || {}),
  };
  /* 유효 공격력이 음수면 하한이 얼마인지 모른다. 0 으로 자르고 그 사실을 밖으로
     알린다 — 조용히 음수를 곱해 부호가 뒤집힌 누적을 내놓는 것보다 낫다. */
  const 방어초과 = 기본.유효공격력 <= 0;
  const 값 = 방어초과 ? 0
    : 칸.기본데미지 * 칸.기본증가 * 칸.버프증가 * 칸.차지계수
      * 칸.우월코드계수 * 칸.받는증가;
  return { 값, 칸, 유효공격력: 기본.유효공격력, 방어초과 };
}

/* 크리 확률을 섞은 기댓값.

   **게임의 규칙이 아니다.** 실제로는 타격마다 난수를 굴린다 (메커니즘 7). 이건
   "난수를 빼면 얼마가 나오는가" 를 볼 때 쓰는 대조용 근사다 — 시뮬레이션 결과가
   씨앗 탓인지 편성 탓인지 가를 때 기준선이 있으면 편하다.

   엔진은 이걸 안 쓴다. 엔진은 `rollCrit()` 로 한 대씩 굴린다. */
export function 기댓값(input, 크리확률) {
  const p = Math.min(Math.max(크리확률 || 0, 0), 1);
  const 크리 = 대미지({ ...input, 기본증가: { ...(input.기본증가 || {}), 크리티컬: true } });
  const 일반 = 대미지({ ...input, 기본증가: { ...(input.기본증가 || {}), 크리티컬: false } });
  return {
    값: 크리.값 * p + 일반.값 * (1 - p),
    크리, 일반, 크리확률: p,
  };
}
